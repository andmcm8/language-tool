const INDEX = new Map<string, string[]>();
for (const entry of PAIRS) {
  for (const key of entry) {
    const k = key.trim().toLowerCase();
    if (!INDEX.has(k)) INDEX.set(k, entry);
  }
}

/** Return `raw` in the requested language when we know it, otherwise unchanged. */
export function labelFor(raw: string, lang: "es" | "en"): string {
  const entry = INDEX.get(raw.trim().toLowerCase());
  if (!entry) return raw;
  return lang === "es" ? entry[1] : entry[0];
}
