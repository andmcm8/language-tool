#!/usr/bin/env python3
"""
Menu accuracy audit: sorts every merchant into
  SOURCED   - listed in data/verified-menus.json: menu was taken from the place's
              real online menu. Entries with "checked": null were transcribed by
              Antigravity and not re-checked yet.
  GENERATED - menu was written by the Gemini generator (generate_custom_merchants.py
              and the "expand menus to 25-35 items" passes). Items, prices, hours
              and even addresses may be invented and must not be trusted.
Writes data/MENU_AUDIT.md.  Run: python3 scraper/audit_menus.py
"""
import glob, json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MERCHANTS = os.path.join(ROOT, "data", "merchants")
VERIFIED_PATH = os.path.join(ROOT, "data", "verified-menus.json")


def sourced_slugs():
    """data/verified-menus.json is the source of truth (the site reads it too)."""
    return set(json.load(open(VERIFIED_PATH)))


def main():
    sourced = sourced_slugs()
    rows = []
    for f in sorted(glob.glob(os.path.join(MERCHANTS, "*.json"))):
        slug = os.path.basename(f)[:-5]
        if slug in ("demo", "elsol"):
            continue
        d = json.load(open(f))
        s = d["storeInfo"]
        rows.append((slug in sourced, slug, s.get("name", ""), s.get("address", ""), len(d.get("products", []))))

    src = [r for r in rows if r[0]]
    gen = [r for r in rows if not r[0]]
    lines = [
        "# Menu Accuracy Audit",
        "",
        "Generated by `scraper/audit_menus.py`.",
        "",
        f"- **Sourced from the real menu:** {len(src)} pages",
        f"- **AI-generated (not trustworthy):** {len(gen)} pages (shown with an \"Unverified menu\" notice)",
        "",
        "To mark a menu verified after checking it, add its slug to `data/verified-menus.json`",
        "with the source URL and date, then re-run this script.",
        "",
        "AI-generated pages came from `generate_custom_merchants.py`, whose prompt told Gemini to use a",
        "\"realistic CT address\" and \"realistic hours\" when it couldn't find them, and from the",
        "\"expand menus to 25-35 items\" passes that padded menus with plausible dishes.",
        "",
        "## Sourced",
        "",
        "| Page | Name | Address | Items |",
        "|---|---|---|---|",
    ]
    lines += [f"| `{r[1]}` | {r[2]} | {r[3]} | {r[4]} |" for r in src]
    lines += ["", "## AI-generated", "", "| Page | Name | Address | Items |", "|---|---|---|---|"]
    lines += [f"| `{r[1]}` | {r[2]} | {r[3]} | {r[4]} |" for r in gen]
    open(os.path.join(ROOT, "data", "MENU_AUDIT.md"), "w").write("\n".join(lines) + "\n")
    print(f"sourced={len(src)} generated={len(gen)} -> data/MENU_AUDIT.md")


if __name__ == "__main__":
    main()
